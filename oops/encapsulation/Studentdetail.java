package oops.encapsulation;

public class Studentdetail {
    private String name;
    private int age;
    private int regno;

    public String getName(){
        return name;
    }
    public void setName(String name){
        this.name=name;
    }

    public int getAge(){
        return age;
    }
    public void setAge(int age){
        this.age=age;
    }

    public int getRegno(){
        return regno;
    }
    public void setRegno(int regno){
        this.regno=regno;
    }
}
